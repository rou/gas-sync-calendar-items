import { build } from 'esbuild';
import { copyFileSync, mkdirSync, readFileSync } from 'node:fs';

// GAS はトップレベルの function 宣言しか関数一覧・トリガーに出さない。
// バンドルは IIFE でグローバル __calendarSync に export を集め、
// footer で同名の function 宣言を生やして委譲する。
const mainSource = readFileSync('src/main.ts', 'utf8');
const exported = [...mainSource.matchAll(/^export function (\w+)\s*\(/gm)].map((m) => m[1]);

const footer = exported
  .map((name) => `function ${name}() { return __calendarSync.${name}.apply(this, arguments); }`)
  .join('\n');

mkdirSync('dist', { recursive: true });

await build({
  entryPoints: ['src/main.ts'],
  bundle: true,
  format: 'iife',
  globalName: '__calendarSync',
  target: 'es2019',
  platform: 'neutral',
  outfile: 'dist/bundle.js',
  banner: { js: '// Generated by esbuild from src/. Do not edit by hand.' },
  footer: { js: footer },
  logLevel: 'info',
});

copyFileSync('src/appsscript.json', 'dist/appsscript.json');
console.log(`exposed: ${exported.join(', ')}`);
